#!/usr/bin/env python3
"""Regenerate Brain's shared and local Markdown indexes."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from okf import parse


SHARED_FOLDERS = (
    "patterns",
    "lessons",
    "decisions",
    "concepts",
    "snippets",
    "sources",
    "infra",
)
GENERATED_NAMES = {"MEMORY.md", "MEMORY.local.md", "index.md"}


@dataclass(frozen=True)
class Entry:
    path: Path
    title: str
    description: str
    entry_type: str
    tags: tuple[str, ...]


def first_heading(path: Path) -> str | None:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return None


def entry_for(path: Path, root: Path) -> Entry | None:
    metadata = parse(path).metadata
    if not metadata.get("type"):
        return None
    title = str(metadata.get("title") or first_heading(path) or path.stem.replace("-", " ").title())
    description = str(metadata.get("description") or "No description provided.")
    entry_type = str(metadata.get("type") or "note")
    raw_tags = metadata.get("tags", ())
    tags = tuple(str(tag) for tag in raw_tags) if isinstance(raw_tags, (list, tuple)) else ()
    return Entry(path.relative_to(root), title, description, entry_type, tags)


def collect(root: Path, paths: list[Path]) -> list[Entry]:
    files: set[Path] = set()
    for base in paths:
        if base.exists():
            files.update(
                path
                for path in base.rglob("*.md")
                if path.name not in GENERATED_NAMES and ".git" not in path.parts
            )
    entries = (entry_for(path, root) for path in files)
    return sorted(
        (entry for entry in entries if entry is not None),
        key=lambda item: str(item.path),
    )


def markdown_link(path: Path, label: str) -> str:
    target = str(path).replace(" ", "%20")
    return f"[{label}]({target})"


def render_folder_index(folder: str, entries: list[Entry]) -> str:
    lines = [
        "---",
        "type: index",
        f"title: {folder.title()} index",
        f"description: Generated catalog of shared Brain entries in {folder}.",
        "tags: [knowledge-management]",
        "---",
        "",
        f"# {folder.title()}",
        "",
        "Generated by `bin/reindex.py`. Do not edit by hand.",
        "",
    ]
    if not entries:
        lines.extend(("_No entries._", ""))
    else:
        for entry in entries:
            target = Path(entry.path.name)
            tags = f" — `{', '.join(entry.tags)}`" if entry.tags else ""
            lines.append(
                f"- {markdown_link(target, entry.title)} — {entry.description}{tags}"
            )
        lines.append("")
    return "\n".join(lines)


def render_shared(entries: list[Entry]) -> str:
    lines = [
        "# Brain memory index",
        "",
        "Generated by `bin/reindex.py`. Do not edit by hand.",
        "",
    ]
    by_folder: dict[str, list[Entry]] = {folder: [] for folder in SHARED_FOLDERS}
    for entry in entries:
        by_folder.setdefault(entry.path.parts[0], []).append(entry)

    for folder in SHARED_FOLDERS:
        lines.extend((f"## {folder.title()}", ""))
        lines.append(f"- {markdown_link(Path(folder) / 'index.md', f'{folder.title()} index')}")
        if not by_folder[folder]:
            lines.append("")
            continue
        for entry in by_folder[folder]:
            tags = f" — `{', '.join(entry.tags)}`" if entry.tags else ""
            lines.append(
                f"- {markdown_link(entry.path, entry.title)} — {entry.description}{tags}"
            )
        lines.append("")
    return "\n".join(lines)


def render_local(entries: list[Entry]) -> str:
    lines = [
        "# Local memory index",
        "",
        "Generated by `bin/reindex.py`. This file and everything under `local/` are gitignored.",
        "",
        "## Privacy boundary",
        "",
        "Personal identity, machine-specific paths, secrets, customer/client names, confidential detail, named engagements, checkpoints, and session transcripts stay in `local/`.",
        "Promotion into shared knowledge is always a separate human-reviewed editorial action.",
        "",
        "Shared-layer denylist terms are stored one per line in `local/shared-denylist.txt`.",
        "",
        "## Entries",
        "",
    ]
    if not entries:
        lines.extend(("_No local entries._", ""))
    else:
        for entry in entries:
            relative_target = entry.path.relative_to("local")
            lines.append(
                f"- {markdown_link(relative_target, entry.title)} — {entry.description}"
            )
        lines.append("")
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> bool:
    normalized = content.rstrip() + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == normalized:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(normalized, encoding="utf-8")
    return True


def reindex(root: Path) -> tuple[bool, bool]:
    shared = collect(root, [root / folder for folder in SHARED_FOLDERS])
    local_root = root / "local"
    local = collect(root, [local_root])
    shared_changed = write_if_changed(root / "MEMORY.md", render_shared(shared))
    for folder in SHARED_FOLDERS:
        folder_entries = [entry for entry in shared if entry.path.parts[0] == folder]
        shared_changed = (
            write_if_changed(root / folder / "index.md", render_folder_index(folder, folder_entries))
            or shared_changed
        )
    local_changed = write_if_changed(local_root / "MEMORY.local.md", render_local(local))
    return shared_changed, local_changed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[1]
    )
    args = parser.parse_args()
    shared_changed, local_changed = reindex(args.root.resolve())
    changed = [
        name
        for name, value in (("MEMORY.md", shared_changed), ("local/MEMORY.local.md", local_changed))
        if value
    ]
    print("updated " + ", ".join(changed) if changed else "indexes already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
